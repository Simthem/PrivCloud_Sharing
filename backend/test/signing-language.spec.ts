/** Text drawn by pdf-lib, read back from the deflated content streams. */
function drawnText(pdf: Buffer): string {
  const raw = pdf.toString("latin1");
  const shown: string[] = [];
  const streams = /stream\r?\n([\s\S]*?)\r?\nendstream/g;
  for (const match of raw.matchAll(streams)) {
    let content: string;
    try {
      content = inflateSync(Buffer.from(match[1], "latin1")).toString("latin1");
    } catch {
      content = match[1];
    }
    for (const hex of content.matchAll(/<([0-9A-Fa-f]+)>\s*Tj/g)) {
      shown.push(Buffer.from(hex[1], "hex").toString("latin1"));
    }
  }
  return shown.join("\n");
}

const signer = {
  name: "Alice Martin",
  email: "alice@example.test",
  signedAt: new Date("2026-11-07T10:00:00Z"),
  signatureType: "DRAWN",
  authenticationMethod: "EMAIL_OTP_CONSENT",
  identityVerificationMethod: "EMAIL_OTP",
};

const dossier = (language: "fr" | "en", signatureLevel: string) =>
  new PdfSigningService().generateCertificatePage({
    documentId: "doc-1",
    fileName: "contract.pdf",
    language,
    signedAt: new Date("2026-11-07T10:05:00Z"),
    signers: [signer],
    documentHash: "ab".repeat(32),
    signatureLevel,
  });

testCase(
  "an unknown or missing language keeps older requests in French",
  () => {
    assert.equal(signingLanguage("en"), "en");
    assert.equal(signingLanguage("fr"), "fr");
    assert.equal(signingLanguage(null), "fr");
    assert.equal(signingLanguage("de"), "fr");
  },
);

testCase("the approval marks follow the requester's language", () => {
  const date = new Date("2026-11-07T10:00:00Z");
  assert.equal(
    approvalMention(date, "fr"),
    "Lu et approuvé le 7 novembre 2026",
  );
  assert.equal(
    approvalMention(date, "en"),
    "Read and approved on 7 November 2026",
  );
  assert.equal(signedFileName("a.pdf", "fr"), "a_signé.pdf");
  assert.equal(signedFileName("a.pdf", "en"), "a_signed.pdf");
  assert.equal(signedFileName("Contrat.PDF", "fr"), "Contrat_signé.pdf");
  assert.equal(signedFileName("a.pdf.pdf", "en"), "a.pdf_signed.pdf");
  assert.equal(signedFileName("scan", "fr"), "scan_signé.pdf");
});

testCase("an empty DATE field is written in the requester's language", () => {
  const field = {
    id: "date",
    type: "DATE",
    label: null,
    required: false,
    assignedRecipientId: null,
  };
  const [english] = collectRecipientFieldValues("alice", [field], [], "en");
  const [french] = collectRecipientFieldValues("alice", [field], [], "fr");
  assert.match(english.value, /^\d{1,2} [A-Z][a-z]+ \d{4}$/);
  assert.match(french.value, /^\d{1,2} [a-zéû]+ \d{4}$/);
});

testCase("an English request yields an English evidence dossier", async () => {
  for (const level of ["STANDARD", "REINFORCED"]) {
    const text = drawnText(await dossier("en", level));
    assert.match(text, /ELECTRONIC SIGNATURE EVIDENCE DOSSIER/);
    assert.match(text, /Signed on: 7 November 2026/);
    assert.match(text, /LEGAL NOTICE/);
    assert.match(text, /Generated by PrivCloud Sharing/);
    assert.doesNotMatch(text, /Signataire|Empreinte|MENTION|Généré|Méthode/);
  }
  const french = drawnText(await dossier("fr", "STANDARD"));
  assert.match(french, /DOSSIER DE PREUVE DE SIGNATURE/);
  assert.match(french, /Signé le: 7 novembre 2026/);
});

testCase(
  "every legal line fits the dossier width in both languages",
  async () => {
    const pdf = await PDFDocument.create();
    const font = await pdf.embedFont(StandardFonts.Helvetica);
    for (const language of ["fr", "en"] as const) {
      const text = dossierText(language);
      for (const line of [
        ...text.legalIntro,
        ...text.legalReinforced,
        ...text.legalStandard,
        ...text.legalOutro,
      ]) {
        assert.ok(
          font.widthOfTextAtSize(line, 8) <= 470,
          `${language} line overflows: ${line}`,
        );
      }
    }
  },
);

testCase(
  "the stamp drawn on the PDF uses the requester's language",
  async () => {
    const source = await PDFDocument.create();
    source.addPage([595.28, 841.89]);
    const stamped = await new PdfSigningService().addApprovalFieldAndSignature(
      Buffer.from(await source.save()),
      {
        name: "Alice Martin",
        signatureText: "Alice",
        signedDate: new Date("2026-11-07T10:00:00Z"),
      },
      { addApprovalWatermark: true, addApprovalMention: true, language: "en" },
    );
    const text = drawnText(stamped);
    assert.match(text, /Read and approved on 7 November 2026/);
    assert.match(text, /^Approved$/m);
    assert.doesNotMatch(text, /Lu et approuv|Bon pour Accord/);
  },
);

testCase(
  "completion mails are written in the requester's language",
  async () => {
    const mails: string[] = [];
    await deliverSigningCompletionEmails({
      fileName: "contract.pdf",
      language: "en",
      documentUrl: "https://example.test/signing/doc-1",
      creator: { email: "owner@example.test", username: "Owner" },
      recipients: [
        {
          email: "alice@example.test",
          name: "Alice",
          role: "SIGNER",
          signedAt: new Date("2026-11-07T10:00:00Z"),
        },
      ],
      sendMail: async (_email, subject, body) => {
        mails.push(`${subject}\n${body}`);
      },
    });
    assert.equal(mails.length, 2);
    for (const mail of mails) {
      assert.match(mail, /^Document signed/);
      assert.match(mail, /signed on 7 November 2026/);
      assert.match(mail, /Electronic Signature$/);
      assert.doesNotMatch(mail, /Bonjour|signé|Signataires/);
    }
  },
);

testCase("the PDF honors separate signature and watermark pages", async () => {
  const source = await PDFDocument.create();
  for (let index = 0; index < 3; index += 1) source.addPage([595, 842]);
  for (const [signaturePage, watermarkPage] of [
    [3, 1],
    [2, 3],
  ]) {
    const stamped = await new PdfSigningService().addApprovalFieldAndSignature(
      Buffer.from(await source.save()),
      {
        name: "Page Choice",
        signatureText: "ManualChoice",
        signedDate: new Date("2026-11-08T10:00:00Z"),
      },
      {
        addApprovalWatermark: true,
        addApprovalMention: false,
        language: "en",
        signaturePage,
        watermarkPage,
        signatureField: {
          page: signaturePage,
          posX: 50,
          posY: 120,
          width: 200,
          height: 60,
        },
      },
    );
    const pdf = await PDFDocument.load(stamped);
    assert.equal(pdf.getPageCount(), 3);
    for (let index = 0; index < 3; index += 1) {
      const single = await PDFDocument.create();
      const [page] = await single.copyPages(pdf, [index]);
      single.addPage(page);
      const text = drawnText(Buffer.from(await single.save()));
      assert.equal(text.includes("ManualChoice"), index + 1 === signaturePage);
      assert.equal(text.includes("Approved"), index + 1 === watermarkPage);
    }
  }
});

void run();
