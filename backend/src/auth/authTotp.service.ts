import {
  BadRequestException,
  ForbiddenException,
  Injectable,
  UnauthorizedException,
} from "@nestjs/common";
import { User } from "@prisma/client";
import { generateSecret, verify, generateURI } from "otplib";
import { createGuardrails } from "@otplib/core";
import * as argon from "argon2";
import * as crypto from "crypto";
import qrcode from "qrcode-svg";
import { ConfigService } from "src/config/config.service";
import { PrismaService } from "src/prisma/prisma.service";
import { assertEmailVerificationAccess } from "src/emailVerification/emailVerification.util";
import { AuthService } from "./auth.service";
import { AuthSignInTotpDTO } from "./dto/authSignInTotp.dto";

import { OAuthReauthPurpose, OAuthReauthService } from "./oauthReauth.service";
export type TotpStepUp = { password?: string; reauthProof?: string };

const BACKUP_CODE_COUNT = 10;

@Injectable()
export class AuthTotpService {
  // Accept legacy 10-byte (80-bit) TOTP secrets stored before otplib v13.
  // New secrets generated by generateSecret() are 20 bytes (160 bits).
  private readonly legacyGuardrails = createGuardrails({
    MIN_SECRET_BYTES: 10,
  });

  constructor(
    private prisma: PrismaService,
    private configService: ConfigService,
    private authService: AuthService,
    private oauthReauth: OAuthReauthService,
  ) {}

  /**
   * Confirms a 2FA change. A given password is always checked (local or
   * LDAP). Without one, only an account that still has a linked OAuth
   * provider may present the proof of a fresh sign-in with that provider. The
   * proof is spent by the step that completes the change.
   */
  private async assertStepUp(
    user: User,
    credentials: TotpStepUp,
    purpose: OAuthReauthPurpose = "TOTP",
  ): Promise<"password" | "oauth"> {
    if (credentials.password) {
      if (!(await this.authService.verifyPassword(user, credentials.password)))
        throw new ForbiddenException("Invalid password");
      return "password";
    }
    const linked = await this.prisma.oAuthUser.count({
      where: { userId: user.id },
    });
    if (
      linked === 0 ||
      !(await this.oauthReauth.hasProof(
        credentials.reauthProof,
        user.id,
        purpose,
      ))
    ) {
      throw new ForbiddenException(
        linked === 0
          ? "Invalid password"
          : "Sign in again with your linked account",
      );
    }
    return "oauth";
  }

  private async spendStepUp(
    user: User,
    method: "password" | "oauth",
    credentials: TotpStepUp,
    purpose: OAuthReauthPurpose = "TOTP",
  ) {
    if (
      method === "oauth" &&
      !(await this.oauthReauth.consumeProof(
        credentials.reauthProof,
        user.id,
        purpose,
      ))
    ) {
      throw new ForbiddenException("Sign in again with your linked account");
    }
  }

  // -- Backup code helpers ----------------------------------------

  private generateBackupCodes(): string[] {
    const codes: string[] = [];
    for (let i = 0; i < BACKUP_CODE_COUNT; i++) {
      // 8-char alphanumeric uppercase, e.g. "A1B2C3D4"
      codes.push(
        crypto.randomBytes(5).toString("hex").toUpperCase().slice(0, 8),
      );
    }
    return codes;
  }

  private async hashAndStoreBackupCodes(
    userId: string,
    codes: string[],
  ): Promise<void> {
    // Delete any existing backup codes for this user
    await this.prisma.totpBackupCode.deleteMany({ where: { userId } });

    // Hash and store all codes
    const records = await Promise.all(
      codes.map(async (code) => ({
        codeHash: await argon.hash(code),
        userId,
      })),
    );

    await this.prisma.totpBackupCode.createMany({ data: records });
  }

  /**
   * Try to match a code against unused backup codes.
   * If matched, marks it as used and returns true.
   */
  private async tryBackupCode(userId: string, code: string): Promise<boolean> {
    const unused = await this.prisma.totpBackupCode.findMany({
      where: { userId, usedAt: null },
    });

    for (const entry of unused) {
      if (await argon.verify(entry.codeHash, code.toUpperCase())) {
        await this.prisma.totpBackupCode.update({
          where: { id: entry.id },
          data: { usedAt: new Date() },
        });
        return true;
      }
    }
    return false;
  }

  /**
   * Verify a TOTP code OR a backup code.
   * Returns true if either succeeds.
   */
  private async verifyTotpOrBackup(
    userId: string,
    totpSecret: string,
    code: string,
  ): Promise<boolean> {
    // Try TOTP first (6-digit codes)
    if (/^\d{6}$/.test(code)) {
      const result = await verify({
        secret: totpSecret,
        token: code,
        guardrails: this.legacyGuardrails,
      });
      if (result.valid) return true;
    }

    // Try backup code (8-char alphanumeric)
    return this.tryBackupCode(userId, code);
  }

  /** A code typed to confirm a change counts towards the account's lock. */
  private verifyStepUpCode(user: User, totpSecret: string, code: string) {
    return this.authService.countReauthentication(user.id, () =>
      this.verifyTotpOrBackup(user.id, totpSecret, code),
    );
  }

  // -- Sign in with TOTP -----------------------------------------

  async signInTotp(dto: AuthSignInTotpDTO) {
    const tokenHash = crypto
      .createHash("sha256")
      .update(dto.loginToken)
      .digest("hex");
    const token =
      (await this.prisma.loginToken.findFirst({
        where: { token: tokenHash },
        include: { user: true },
      })) ??
      // Five-minute compatibility window for tokens minted before hashing.
      (await this.prisma.loginToken.findFirst({
        where: { token: dto.loginToken },
        include: { user: true },
      }));

    if (!token || token.used)
      throw new UnauthorizedException("Invalid login token");

    if (token.expiresAt < new Date())
      throw new UnauthorizedException("Login token expired", "token_expired");

    assertEmailVerificationAccess(token.user);

    // Check the TOTP code
    const { totpSecret } = token.user;

    if (!totpSecret) {
      throw new BadRequestException("TOTP is not enabled");
    }

    // Reserve a code check before verification so concurrent requests share
    // the same five-attempt limit, including tokens created by older servers.
    const reserved = await this.prisma.loginToken.updateMany({
      where: {
        token: token.token,
        used: false,
        expiresAt: { gt: new Date() },
        attempts: { lt: 5 },
      },
      data: { attempts: { increment: 1 } },
    });
    if (reserved.count !== 1) {
      throw new UnauthorizedException("Invalid login token");
    }

    // Counted towards the account's lock as well: a new login token per
    // correct password must not mean five fresh guesses each time.
    if (
      !(await this.authService.countReauthentication(token.user.id, () =>
        this.verifyTotpOrBackup(token.user.id, totpSecret, dto.totp),
      ))
    ) {
      throw new BadRequestException("Invalid code");
    }
    // The sign-in is complete: its failure count restarts.
    await this.authService.clearLoginFailures(token.user.id);

    // Consume the one-time token atomically. Two valid TOTP requests can race;
    // only the request that changes `used` from false to true may create a
    // session.
    const consumed = await this.prisma.loginToken.updateMany({
      where: {
        token: token.token,
        used: false,
        expiresAt: { gt: new Date() },
      },
      data: { used: true },
    });
    if (consumed.count !== 1) {
      throw new UnauthorizedException("Invalid login token");
    }

    const { refreshToken, refreshTokenId } =
      await this.authService.createRefreshToken(token.user.id);
    const accessToken = await this.authService.createAccessToken(
      token.user,
      refreshTokenId,
    );

    return { accessToken, refreshToken };
  }

  // -- Enable TOTP -----------------------------------------------

  async enableTotp(user: User, credentials: TotpStepUp) {
    // Only checked here: the proof stays valid for the verification step.
    await this.assertStepUp(user, credentials);

    // Check if we have a secret already
    const { totpVerified } = await this.prisma.user.findUnique({
      where: { id: user.id },
      select: { totpVerified: true },
    });

    if (totpVerified) {
      throw new BadRequestException("TOTP is already enabled");
    }

    const issuer = this.configService.get("general.appName");
    const secret = generateSecret();

    const otpURL = generateURI({
      issuer,
      label: user.username || user.email,
      secret,
    });

    await this.prisma.user.update({
      where: { id: user.id },
      data: {
        totpEnabled: true,
        totpSecret: secret,
      },
    });

    // TODO: Maybe we should generate the QR code on the client rather than the server?
    const qrCode = new qrcode({
      content: otpURL,
      container: "svg-viewbox",
      join: true,
    }).svg();

    return {
      totpAuthUrl: otpURL,
      totpSecret: secret,
      qrCode:
        "data:image/svg+xml;base64," + Buffer.from(qrCode).toString("base64"),
    };
  }

  // -- Verify TOTP (finalize activation + generate backup codes) -

  async verifyTotp(user: User, credentials: TotpStepUp, code: string) {
    const method = await this.assertStepUp(user, credentials);

    const { totpSecret } = await this.prisma.user.findUnique({
      where: { id: user.id },
      select: { totpSecret: true },
    });

    if (!totpSecret) {
      throw new BadRequestException("TOTP is not in progress");
    }

    if (
      !(
        await verify({
          secret: totpSecret,
          token: code,
          guardrails: this.legacyGuardrails,
        })
      ).valid
    ) {
      throw new BadRequestException("Invalid code");
    }

    await this.spendStepUp(user, method, credentials);

    await this.prisma.user.update({
      where: { id: user.id },
      data: {
        totpVerified: true,
      },
    });

    // Generate backup codes and return them in plaintext (only time they're shown)
    const backupCodes = this.generateBackupCodes();
    await this.hashAndStoreBackupCodes(user.id, backupCodes);

    return { backupCodes };
  }

  // -- Disable TOTP (accepts TOTP code OR backup code) -----------

  async disableTotp(user: User, credentials: TotpStepUp, code: string) {
    const method = await this.assertStepUp(user, credentials);

    const { totpSecret } = await this.prisma.user.findUnique({
      where: { id: user.id },
      select: { totpSecret: true },
    });

    if (!totpSecret) {
      throw new BadRequestException("TOTP is not enabled");
    }

    if (!(await this.verifyStepUpCode(user, totpSecret, code))) {
      throw new BadRequestException("Invalid code");
    }
    await this.spendStepUp(user, method, credentials);

    await this.prisma.$transaction([
      this.prisma.totpBackupCode.deleteMany({ where: { userId: user.id } }),
      this.prisma.user.update({
        where: { id: user.id },
        data: {
          totpVerified: false,
          totpEnabled: false,
          totpSecret: null,
        },
      }),
    ]);

    return true;
  }

  // -- Changes as strong as turning 2FA off ----------------------

  /**
   * Confirms a change that lets someone sign in without the second factor,
   * such as adding a passkey: the password (or a fresh linked OAuth sign-in)
   * and, when 2FA is on, a current code. The same proof as disabling 2FA.
   */
  /**
   * The proof of a 2FA change, also asked of an administrator before a
   * sensitive operation (`ADMIN`): the password or a fresh linked sign-in,
   * plus the current code when 2FA is on. Returns the factor that was proven.
   */
  async confirmSecondFactorChange(
    user: User,
    credentials: TotpStepUp,
    code?: string,
    purpose: OAuthReauthPurpose = "TOTP",
  ) {
    const method = await this.assertStepUp(user, credentials, purpose);
    if (user.totpVerified) {
      const stored = await this.prisma.user.findUnique({
        where: { id: user.id },
        select: { totpSecret: true },
      });
      if (
        !code ||
        !stored?.totpSecret ||
        !(await this.verifyStepUpCode(user, stored.totpSecret, code))
      ) {
        throw new BadRequestException("Invalid code");
      }
    }
    await this.spendStepUp(user, method, credentials, purpose);
    return method;
  }

  async confirmEmailChangeFactor(user: User, code?: string) {
    if (
      user.totpVerified &&
      (!user.totpSecret ||
        !code ||
        !(await this.verifyStepUpCode(user, user.totpSecret, code)))
    ) {
      throw new BadRequestException("Invalid code");
    }
  }

  // -- Admin: force-disable TOTP for a user ----------------------

  async adminDisableTotp(userId: string) {
    const user = await this.prisma.user.findUnique({
      where: { id: userId },
      select: { totpEnabled: true, totpVerified: true, totpSecret: true },
    });

    if (!user) {
      throw new BadRequestException("User not found");
    }

    // Sign-in asks for a code as soon as totpVerified is set. Any trace of a
    // second factor must therefore be resettable, not only a complete one.
    if (!user.totpEnabled && !user.totpVerified && !user.totpSecret) {
      throw new BadRequestException("TOTP is not enabled for this user");
    }

    await this.prisma.$transaction([
      this.prisma.totpBackupCode.deleteMany({ where: { userId } }),
      this.prisma.loginToken.deleteMany({ where: { userId } }),
      this.prisma.user.update({
        where: { id: userId },
        data: {
          totpVerified: false,
          totpEnabled: false,
          totpSecret: null,
        },
      }),
    ]);

    return true;
  }
}
